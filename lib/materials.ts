/** 珠子尺寸（mm） */
export type BeadSize = 4 | 6 | 8 | 10 | 12;

export type MaterialCategory = 'bead' | 'accessory' | 'pendant' | 'wood';
export type MaterialShape = 'sphere' | 'disc' | 'pendant';
export type TextureKey =
  | 'cat-eye-pink'
  | 'cat-eye-blue'
  | 'obsidian'
  | 'silver-sand'
  | 'wood-rosewood'
  | 'wood-ebony'
  | 'jasmine'
  | 'gourd'
  | 'fu-char'
  | 'gold'
  | 'silver'
  | 'frost';

export interface Material {
  id: string;
  name: string;
  category: MaterialCategory;
  /** 子分類（依主分類切換） */
  sub: string;
  /** 可選尺寸（mm） */
  sizes: number[];
  shape: MaterialShape;
  color: string;
  accent: string;
  inner: string;
  /** 透射吸收色（明亮色系） */
  attenuation: string;
  emissive: string;
  emissiveIntensity: number;
  transmission: number;
  ior: number;
  roughness: number;
  metalness: number;
  clearcoat: number;
  iridescence: number;
  sheen: number;
  sheenColor: string;
  density: number;
  /** 程序化紋理鍵 */
  texture?: TextureKey;
  /** 材質寓意與功效 */
  meaning: string;
  /** 庫存不足時卡片顯示遮罩 */
  stock?: boolean;
  /** 吊墜掛在圓環 12 點鐘方向外側 */
  pendant?: boolean;
}

